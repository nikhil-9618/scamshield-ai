export function riskLevelFromScore(score: number): RiskLevel {
  const bounded = Math.max(0, Math.min(100, Math.round(score)));
  if (bounded <= RISK_THRESHOLDS.lowMax) return 'low';
  if (bounded <= RISK_THRESHOLDS.moderateMax) return 'moderate';
  if (bounded <= RISK_THRESHOLDS.highMax) return 'high';
  return 'critical';
}

